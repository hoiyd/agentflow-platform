import { test, expect } from "@playwright/test";
import { writeFile } from "node:fs/promises";
import { createWorkspaceChatAgent, defaultWorkspaceID } from "./fixtures/workspace-agent";

test("Workspace MCP connections: UI lifecycle, real calls and durable Replay", async ({ page, request }) => {
  test.skip(process.env.AGENTFLOW_MCP_CONNECTION_TEST !== "1", "requires isolated MCP connection fixture");
  test.setTimeout(180_000);
  await page.goto("/workspace");
  await expect(page.getByText("API connected", { exact: true })).toBeVisible();
  const workspace = await defaultWorkspaceID(page);
  const headers = { "X-Workspace-ID": workspace };
  const fixture = await (await request.get("http://127.0.0.1:18080/__fixture/mcp")).json();
  await page.getByRole("button", { name: "Tools", exact: true }).click();
  await page.getByRole("button", { name: "MCP connections", exact: true }).click();
  await page.getByRole("button", { name: "Add connection", exact: true }).click();
  await page.getByLabel("Connection name", { exact: true }).fill("Documentation service");
  await page.getByLabel("Endpoint URL", { exact: true }).fill(fixture.endpoint);
  await page.getByRole("button", { name: "Authentication: None", exact: true }).click();
  await page.getByRole("option", { name: "Bearer token", exact: true }).click();
  await page.getByLabel("Bearer token", { exact: true }).fill("wrong-token");
  await page.getByRole("button", { name: "Save connection", exact: true }).click();
  const row = page.getByRole("article", { name: "Documentation service", exact: true });
  await row.getByRole("button", { name: "Test connection", exact: true }).click();
  await expect(row.getByText("Authentication failed", { exact: true })).toBeVisible();
  await row.getByRole("button", { name: "Edit connection", exact: true }).click();
  await page.getByLabel("Bearer token", { exact: true }).fill(fixture.token);
  await page.getByRole("button", { name: "Save connection", exact: true }).click();
  await row.getByRole("button", { name: "Test connection", exact: true }).click();
  await expect(row.getByText("Tools discovered", { exact: true })).toBeVisible();
  await row.getByRole("button", { name: "Edit connection", exact: true }).click();
  await page.getByRole("checkbox", { name: "Allow read", exact: true }).check();
  await page.getByRole("checkbox", { name: "Enable connection", exact: true }).check();
  const dialogScreenshot = test.info().outputPath("workspace-mcp-tool-selection.png");
  await page.screenshot({ path: dialogScreenshot });
  await test.info().attach("workspace-mcp-tool-selection.png", { path: dialogScreenshot, contentType: "image/png" });
  await page.getByRole("button", { name: "Save connection", exact: true }).click();
  await page.reload();
  await page.getByRole("button", { name: "Tools", exact: true }).click();
  await page.getByRole("button", { name: "MCP connections", exact: true }).click();
  await expect(row.getByText("Enabled", { exact: true })).toBeVisible();
  const list = await (await request.get("http://127.0.0.1:18080/api/mcp/connections", { headers })).json();
  const connection = list.find((c: { name: string }) => c.name === "Documentation service");
  expect(JSON.stringify(list)).not.toContain(fixture.token);
  const toolName = `mcp_w${connection.id}__read`;
  await page.getByRole("button", { name: "Tool catalog", exact: true }).click();
  const tool = page.locator(".tool-card").filter({ has: page.getByRole("heading", { name: toolName, exact: true }) });
  if (!(await tool.getByRole("checkbox").isChecked())) await tool.getByRole("checkbox").click();
  await expect(tool.getByRole("checkbox")).toBeChecked();
  await page.getByRole("button", { name: "MCP connections", exact: true }).click();
  await expect(row).toBeVisible();
  const screenshot = test.info().outputPath("workspace-mcp-connections.png");
  await page.screenshot({ path: screenshot });
  await test.info().attach("workspace-mcp-connections.png", { path: screenshot, contentType: "image/png" });
  const agent = await createWorkspaceChatAgent(page, workspace, "Workspace docs reader", { tools: [toolName], routing_hints: { capabilities: ["public-docs"], task_examples: ["mcp-gate"], exclusions: [] } });
  const runs = [];
  for (const mode of ["Single agent", "Multi-agent", "Bounded loop"]) {
    await page.getByRole("button", { name: "New conversation", exact: true }).click();
    await page.getByRole("region", { name: "Chat mode" }).getByRole("button", { name: new RegExp(mode) }).click();
    await page.getByPlaceholder("Ask AgentFlow anything...").fill("mcp-gate: read the public project guide");
    await page.getByRole("button", { name: "Send message", exact: true }).click();
    if (mode === "Multi-agent") {
      await page.getByText("Routing requirements", { exact: true }).click();
      await page.getByRole("textbox", { name: "Preferred capabilities", exact: true }).fill("public-docs");
      await page.getByRole("button", { name: "Approve & Continue", exact: true }).click();
    }
    await expect(page.locator(".message.assistant").last()).toContainText("MCP evidence confirmed", { timeout: 45_000 });
    const runID = (await page.getByRole("link", { name: "View trace", exact: true }).getAttribute("href"))!.split("/").at(-1)!;
    const replay = await (await request.get(`http://127.0.0.1:18080/api/runs/${runID}/replay`, { headers })).json();
    expect(replay.run_events.some((e: { type: string; payload: { tool_name?: string } }) => e.type === "tool.completed" && e.payload.tool_name === toolName)).toBe(true);
    expect(JSON.stringify(replay)).not.toContain(fixture.token);
    runs.push({ mode, run_id: runID, source: replay.runtime_snapshot.tools.find((t: { name: string }) => t.name === toolName)?.source });
  }
  await page.getByRole("button", { name: "New conversation", exact: true }).click();
  await page.getByRole("region", { name: "Chat mode" }).getByRole("button", { name: /Multi-agent/ }).click();
  await page.getByPlaceholder("Ask AgentFlow anything...").fill("mcp-gate: read the public project guide");
  await page.getByRole("button", { name: "Send message", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve & Continue", exact: true })).toBeVisible();
  const waitingRun = (await page.getByRole("link", { name: "View trace", exact: true }).getAttribute("href"))!.split("/").at(-1)!;
  const callsBefore = (await (await request.get("http://127.0.0.1:18080/__fixture/mcp")).json()).calls;
  await page.getByRole("button", { name: "Tools", exact: true }).click();
  await page.getByRole("button", { name: "MCP connections", exact: true }).click();
  await row.getByRole("button", { name: "Disable connection", exact: true }).click();
  await expect(row.getByText("Disabled", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Chat", exact: true }).click();
  const continuation = page.waitForResponse(response => response.url().endsWith(`/api/runs/${waitingRun}/continue`));
  await page.getByRole("button", { name: "Approve & Continue", exact: true }).click();
  expect(await (await continuation).text()).toMatch(/frozen tool|no longer installed|unavailable/i);
  const waitingReplay = await (await request.get(`http://127.0.0.1:18080/api/runs/${waitingRun}/replay`, { headers })).json();
  expect(waitingReplay.run.status).toBe("waiting_for_user");
  expect((await (await request.get("http://127.0.0.1:18080/__fixture/mcp")).json()).calls).toBe(callsBefore);
  await page.getByRole("button", { name: "Tools", exact: true }).click();
  await page.getByRole("button", { name: "MCP connections", exact: true }).click();
  await row.getByRole("button", { name: "Delete connection", exact: true }).click();
  await page.getByRole("dialog", { name: "Delete connection" }).getByRole("button", { name: "Delete connection", exact: true }).click();
  await expect(row).toHaveCount(0);
  for (const run of runs) expect((await request.get(`http://127.0.0.1:18080/api/runs/${run.run_id}/replay`, { headers })).ok()).toBe(true);
  const evidence = test.info().outputPath("workspace-mcp-evidence.json");
  await writeFile(evidence, JSON.stringify({ schema: "workspace-mcp-browser-v1", workspace_id: workspace, connection_id: connection.id, agent_id: agent.id, fixture: "app/browser_mcp_test.go", transport: "streamable_http", task: "mcp-gate: read the public project guide", runs, rejected_continuation: { run_id: waitingRun, status: waitingReplay.run.status, calls_before: callsBefore, calls_after: callsBefore }, checks: ["UI authentication failure and correction", "discovery without grants", "explicit reviewed tool selection", "reload persistence", "three runtime modes", "secret-free Replay", "disabled connection blocks frozen continuation without invocation", "disable and delete preserve historical evidence"], limitations: ["synthetic model and MCP service; not live model quality"] }, null, 2));
  await test.info().attach("workspace-mcp-evidence.json", { path: evidence, contentType: "application/json" });
});
